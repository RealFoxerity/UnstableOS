void transform_block(unsigned char * block, size_t bs, uint16_t convs) {
    if (convs & 0x20) {
        for (size_t i = 0; i < bs/2; i+=2) {
            unsigned char c = block[i*2];
            block[i*2] = block[i*2+1];
            block[i*2+1] = c;
        }
    }
    for (size_t i = 0; i < bs; i++) {
        if (convs & 1) // EBCDIC to ASCII
            block[i] = ebcdic_to_ascii[block[i]];
        if (convs & 0x8)
            block[i] = tolower((char)block[i]);
        if (convs & 0x10)
            block[i] = toupper((char)block[i]);
        if (convs & 2) // ASCII to EBCDIC
            block[i] = ascii_to_ebcdic[block[i]];
        if (convs & 4) // ASCII to IBM EBCDIC
            block[i] = ascii_to_ebcdic[block[i]];
    }
}
